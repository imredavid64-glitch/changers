import type { HealthCheck, PlatformHealthReport } from "../types";

export function formatHealthReportMarkdown(report: PlatformHealthReport): string {
  const lines: string[] = [];
  
  lines.push(`# Changers Platform Health Report`);
  lines.push(``);
  lines.push(`**Status:** ${report.ok ? "✅ HEALTHY" : "⚠️ ISSUES DETECTED"}`);
  lines.push(`**Checked at:** ${new Date(report.checkedAt).toLocaleString()}`);
  lines.push(`**Endpoint:** ${report.endpoint}`);
  lines.push(`**Project:** ${report.projectId}`);
  lines.push(`**Database:** ${report.databaseId}`);
  lines.push(``);
  lines.push(`---`);
  lines.push(``);
  
  const byStatus = {
    fail: report.checks.filter((c) => c.status === "fail"),
    warn: report.checks.filter((c) => c.status === "warn"),
    ok: report.checks.filter((c) => c.status === "ok"),
  };
  
  if (byStatus.fail.length > 0) {
    lines.push(`## ❌ Failed Checks (${byStatus.fail.length})`);
    lines.push(``);
    for (const check of byStatus.fail) {
      lines.push(`### ${check.label}`);
      lines.push(`- **Key:** \`${check.key}\``);
      lines.push(`- **Detail:** ${check.detail}`);
      lines.push(``);
    }
  }
  
  if (byStatus.warn.length > 0) {
    lines.push(`## ⚠️ Warnings (${byStatus.warn.length})`);
    lines.push(``);
    for (const check of byStatus.warn) {
      lines.push(`### ${check.label}`);
      lines.push(`- **Key:** \`${check.key}\``);
      lines.push(`- **Detail:** ${check.detail}`);
      lines.push(``);
    }
  }
  
  if (byStatus.ok.length > 0) {
    lines.push(`## ✅ Passing Checks (${byStatus.ok.length})`);
    lines.push(``);
    for (const check of byStatus.ok) {
      lines.push(`- **${check.label}:** ${check.detail}`);
    }
    lines.push(``);
  }
  
  lines.push(`---`);
  lines.push(``);
  lines.push(`*Generated by Changers DB Agent*`);
  
  return lines.join("\n");
}

export function formatHealthReportJson(report: PlatformHealthReport): string {
  return JSON.stringify(report, null, 2);
}

export function formatHealthReportSummary(report: PlatformHealthReport): string {
  const failCount = report.checks.filter((c) => c.status === "fail").length;
  const warnCount = report.checks.filter((c) => c.status === "warn").length;
  const okCount = report.checks.filter((c) => c.status === "ok").length;
  
  const statusEmoji = report.ok ? "✅" : failCount > 0 ? "❌" : "⚠️";
  
  return `${statusEmoji} Changers DB Health: ${okCount} ok, ${warnCount} warn, ${failCount} fail`;
}

export function getFailedChecks(report: PlatformHealthReport): HealthCheck[] {
  return report.checks.filter((c) => c.status === "fail");
}

export function getWarningChecks(report: PlatformHealthReport): HealthCheck[] {
  return report.checks.filter((c) => c.status === "warn");
}

export function isAutoFixable(check: HealthCheck): boolean {
  const autoFixableKeys = [
    "collections",
    "schema",
    "media-bucket",
    "attr-limit-",
    "index-status-",
  ];
  
  return autoFixableKeys.some((key) => check.key.startsWith(key)) && check.status === "fail";
}

export function getAutoFixableChecks(report: PlatformHealthReport): HealthCheck[] {
  return report.checks.filter((c) => c.status === "fail" && isAutoFixable(c));
}