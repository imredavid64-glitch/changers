#!/usr/bin/env node
// Builds src/lib/network-research.ts from docs/research/network-places.json (the sourced research behind the landing
// globe). Re-run after the research is re-checked:  node scripts/network-research.mjs
import fs from 'node:fs'

const src = new URL('../../docs/research/network-places.json', import.meta.url)
const out = new URL('../src/lib/network-research.ts', import.meta.url)
const j = JSON.parse(fs.readFileSync(src, 'utf8'))
const MONTHS = ['january', 'february', 'march', 'april', 'may', 'june', 'july', 'august', 'september', 'october', 'november', 'december']

// "11–13 March 2027" → "2027-03-13": the last day decides which conference is next.
function ends(dates) {
  const m = dates.match(/(\d{1,2})\s*[–-]\s*(\d{1,2})\s+([A-Za-z]+)\s+(\d{4})/)
  if (!m) throw new Error(`Can't read the end date of "${dates}"`)
  const month = MONTHS.indexOf(m[3].toLowerCase()) + 1
  if (!month) throw new Error(`Unknown month in "${dates}"`)
  return `${m[4]}-${String(month).padStart(2, '0')}-${m[2].padStart(2, '0')}`
}

// The 4 Oct detail pass (docs/research/network-details-*.json): each school's campus, website, profile, what students
// do and what it did at the conference, and each edition's highlights. Every fact keeps its source.
const details = fs.readdirSync(new URL('../../docs/research/', import.meta.url))
  .filter((n) => /^network-details-[a-z]\.json$/.test(n)).sort()
  .map((n) => JSON.parse(fs.readFileSync(new URL(`../../docs/research/${n}`, import.meta.url), 'utf8')))
const bySchool = new Map(details.flatMap((d) => d.schools ?? []).map((s) => [s.name, s]))
const byYear = new Map(details.flatMap((d) => d.conferences ?? []).map((c) => [c.year, c]))
const facts = (list) => (list ?? []).filter((f) => f && f.text && f.source).map((f) => ({ text: f.text, source: f.source }))
// Schools whose identity is unsettled: the name stays (the conference pages print it), the details wait. The 2026
// roster links "Budapest British International School" to a different school (docs/research/network-review-2026-10-06.json).
const HOLD_DETAILS = new Set(['Budapest British International School'])

const conferences = j.conferences.map((c) => ({
  year: c.year, host: c.host, city: c.city, country: c.country, lat: c.lat, lng: c.lng,
  dates: c.dates, ends: ends(c.dates), schools: c.schools ?? null, url: c.url,
  highlights: facts(byYear.get(c.year)?.highlights),
}))
const schools = j.schools.map((s) => {
  const d = HOLD_DETAILS.has(s.name) ? {} : bySchool.get(s.name) ?? {}
  // Places stay city-level (07 §privacy: "never a school address"): the campus coordinates and addresses in the
  // detail files are only used by scripts/map-data.mjs to cut the city tiles, never shipped with the site.
  return {
    name: s.name, city: s.city, country: s.country, lat: Math.round(s.lat * 100) / 100, lng: Math.round(s.lng * 100) / 100,
    years: (s.years ?? []).map((y) => ({ year: y.year, source: y.source })),
    facts: facts(s.facts),
    website: d.website ?? s.website ?? null,
    profile: facts(d.profile), changemaking: facts(d.changemaking),
    conference: (d.conference ?? []).filter((f) => f && f.text && f.source).map((f) => ({ year: f.year ?? null, text: f.text, source: f.source })),
  }
})

const ts = `// GENERATED by scripts/network-research.mjs from docs/research/network-places.json. Don't edit by hand.
// The research layer of the landing globe (Luke, 4 Oct): Changemaker Conference editions and the schools their pages
// list, from public pages only; every fact carries its URL. Shown only in review builds until
// switches.conferenceSchools is on (PRD §5 rule 5). The facts are proposed copy (🟡, docs/05-COPY.md §Network map).

export type ResearchFact = { text: string; source: string }
export type ResearchConference = {
  year: number; host: string; city: string; country: string; lat: number; lng: number
  /** Shown as written; ends is the last day (ISO), which decides which conference is next. */
  dates: string; ends: string; schools: number | null; url: string
  highlights: ResearchFact[]
}
export type ResearchSchool = {
  name: string; city: string; country: string; lat: number; lng: number
  years: { year: number; source: string }[]
  facts: ResearchFact[]
  website: string | null
  profile: ResearchFact[]; changemaking: ResearchFact[]
  conference: (ResearchFact & { year: number | null })[]
}

export const RESEARCH: { checked: string; conferences: ResearchConference[]; schools: ResearchSchool[] } = ${JSON.stringify({ checked: j.checked, conferences, schools }, null, 2)}
`
fs.writeFileSync(out, ts)
const n = schools.reduce((t, s) => t + s.facts.length + s.profile.length + s.changemaking.length + s.conference.length, 0)
  + conferences.reduce((t, c) => t + c.highlights.length, 0)
console.log(`✓ ${conferences.length} conferences, ${schools.length} schools, ${n} facts → src/lib/network-research.ts (checked ${j.checked})`)
